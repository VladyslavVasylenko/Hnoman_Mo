let currentLang = "uk";
let currentPage = 0;
let isSpeaking = false;

const bookTitle = document.getElementById("bookTitle");
const episodeBadge = document.getElementById("episodeBadge");
const pageIndicator = document.getElementById("pageIndicator");
const storyText = document.getElementById("storyText");
const pageImage = document.getElementById("pageImage");
const imageCaption = document.getElementById("imageCaption");
const prevBtn = document.getElementById("prevBtn");
const nextBtn = document.getElementById("nextBtn");
const progressDots = document.getElementById("progressDots");
const langSelect = document.getElementById("langSelect");
const speakBtn = document.getElementById("speakBtn");
const autoPlayToggle = document.getElementById("autoPlayToggle");
const pageCard = document.getElementById("pageCard");

function renderDots() {
  const pages = storyData[currentLang].pages;
  progressDots.innerHTML = "";
  pages.forEach((_, index) => {
    const dot = document.createElement("button");
    dot.className = "dot" + (index === currentPage ? " active" : "");
    dot.ariaLabel = `Сторінка ${index + 1}`;
    dot.addEventListener("click", () => {
      stopSpeech();
      goToPage(index);
    });
    progressDots.appendChild(dot);
  });
}

function renderPage() {
  const data = storyData[currentLang];
  const page = data.pages[currentPage];

  bookTitle.textContent = data.title;
  episodeBadge.textContent = data.episode;
  pageIndicator.textContent = data.pageLabel(currentPage + 1, data.pages.length);

  storyText.innerHTML = page.paragraphs
    .map((p) => `<p>${p}</p>`)
    .join("");

  pageImage.src = page.image;
  pageImage.onerror = () => {
    pageImage.src =
      "data:image/svg+xml;charset=UTF-8," +
      encodeURIComponent(
        `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600">
          <rect width="100%" height="100%" fill="#26382b"/>
          <text x="50%" y="50%" fill="#d8cbb5" font-family="sans-serif" font-size="20" text-anchor="middle">
            Тут буде ілюстрація (${page.image})
          </text>
        </svg>`
      );
  };
  imageCaption.textContent = page.caption;

  prevBtn.disabled = currentPage === 0;
  nextBtn.disabled = currentPage === data.pages.length - 1;
  speakBtn.textContent = isSpeaking ? data.speakStop : data.speakStart;

  renderDots();
}

function goToPage(index) {
  pageCard.classList.add("fade");
  setTimeout(() => {
    currentPage = index;
    renderPage();
    pageCard.classList.remove("fade");
  }, 150);
}

function stopSpeech() {
  if ("speechSynthesis" in window) {
    window.speechSynthesis.cancel();
  }
  isSpeaking = false;
  speakBtn.classList.remove("speaking");
  speakBtn.textContent = storyData[currentLang].speakStart;
}

function speakCurrentPage() {
  if (!("speechSynthesis" in window)) {
    alert("Ваш браузер не підтримує автоматичне озвучення тексту.");
    return;
  }

  window.speechSynthesis.cancel();

  const data = storyData[currentLang];
  const textToRead = data.pages[currentPage].paragraphs.join(" ");
  const utterance = new SpeechSynthesisUtterance(textToRead);

  const langMap = { uk: "uk-UA", ru: "ru-RU", cs: "cs-CZ", en: "en-US" };
  utterance.lang = langMap[currentLang] || "uk-UA";
  utterance.rate = 0.95;

  utterance.onstart = () => {
    isSpeaking = true;
    speakBtn.classList.add("speaking");
    speakBtn.textContent = data.speakStop;
  };

  utterance.onend = () => {
    isSpeaking = false;
    speakBtn.classList.remove("speaking");
    speakBtn.textContent = data.speakStart;

    if (autoPlayToggle.checked && currentPage < data.pages.length - 1) {
      setTimeout(() => {
        goToPage(currentPage + 1);
        setTimeout(speakCurrentPage, 300);
      }, 600);
    }
  };

  utterance.onerror = () => {
    stopSpeech();
  };

  window.speechSynthesis.speak(utterance);
}

prevBtn.addEventListener("click", () => {
  if (currentPage > 0) {
    stopSpeech();
    goToPage(currentPage - 1);
  }
});

nextBtn.addEventListener("click", () => {
  const total = storyData[currentLang].pages.length;
  if (currentPage < total - 1) {
    stopSpeech();
    goToPage(currentPage + 1);
  }
});

speakBtn.addEventListener("click", () => {
  if (isSpeaking) {
    stopSpeech();
  } else {
    speakCurrentPage();
  }
});

langSelect.addEventListener("change", (e) => {
  stopSpeech();
  currentLang = e.target.value;
  currentPage = 0;
  renderPage();
});

renderPage();
